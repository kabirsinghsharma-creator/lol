const splitList = (s) =>
  s
    .split(/[,\n]/)
    .map((x) => x.trim())
    .filter(Boolean)

export const TIERS = ['common', 'rare', 'krillion']

// Parsed categories: { id, title, prompt, emoji, answers: [{ id, name, aliases, tier, rank }] }
export const CATEGORIES = RAW_CATEGORIES.map((c) => {
  const answers = []
  for (const tier of TIERS) {
    const list = splitList(c[tier])
    list.forEach((item, i) => {
      const aliases = item
        .split('/')
        .map((a) => a.trim())
        .filter(Boolean)
      answers.push({
        id: `${c.id}:${tier}:${i}`,
        name: aliases[0],
        aliases,
        tier,
        // 0 → most obvious in tier, approaching 1 → deepest cut
        rank: list.length > 1 ? i / (list.length - 1) : 0,
      })
    })
  }
  return { id: c.id, title: c.title, prompt: c.prompt, emoji: c.emoji, answers }
})
